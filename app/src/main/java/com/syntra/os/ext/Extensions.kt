/*
 * Extension manifest — `syntra-extension.json` in a repo root, or generated by an importer for repos that
 * don't have one (Claude-style SKILL.md, Agency-style persona files, Python packages).
 * Repo scripts are never executed: the only commands Syntra runs are the apt/pip lines below, shown to the user first.
 */
@Serializable data class ExtSkill(val name: String, val file: String, val description: String = "")
@Serializable data class ExtAgent(val name: String, val file: String, val description: String = "")
@Serializable data class ExtTool(
    val name: String, val description: String,
    /** "linux-python" | "linux-shell" — runs inside Syntra's Ubuntu sandbox. */
    val runtime: String = "linux-python",
    /** Repo-relative file, or empty when [inline] holds the script (registry-provided tools). */
    val entry: String = "",
    val inline: String = "",
    /** param name → description; arguments arrive as one JSON object on argv[1]. */
    val params: Map<String, String> = emptyMap(),
    val required: List<String> = emptyList(),
    val timeoutSec: Int = 120,
)
@Serializable data class ExtDeps(val apt: List<String> = emptyList(), val pip: List<String> = emptyList())
@Serializable data class Manifest(
    val id: String, val name: String, val version: String = "0", val type: String = "package",
    val description: String = "",
    val skills: List<ExtSkill> = emptyList(), val agents: List<ExtAgent> = emptyList(), val tools: List<ExtTool> = emptyList(),
    val dependencies: ExtDeps = ExtDeps(), val permissions: List<String> = emptyList(),
    /** Remote MCP servers this extension connects (their tools are approval-gated like any MCP tool). */
    val mcp: List<com.syntra.os.core.McpServer> = emptyList(),
)

/** What will happen if the user approves — shown in full before anything is installed. */
data class InstallPlan(
    val repo: String, val sha: String, val manifest: Manifest, val generated: Boolean,
    /** repo-relative files to download (skill/agent/tool files and skill reference files). */
    val files: List<String>, val bytes: Long,
    val commands: List<String>, val warnings: List<String>,
    /** Scripts present in the repo that Syntra will NOT run (shown for transparency). */
    val ignoredScripts: List<String>,
)

@Serializable data class InstalledExt(
    val manifest: Manifest, val repo: String, val sha: String, val installedAt: Long = System.currentTimeMillis(),
    val enabled: Boolean = true, val toolsReady: Boolean = false, val log: String = "",
)

object Importer {
    private val TEXT = setOf("md", "txt", "json", "yaml", "yml", "py", "sh", "js", "ts", "toml", "csv", "html", "css")
    private const val MAX_FILES = 400
    private const val MAX_BYTES = 6_000_000L

    data class Entry(val path: String, val size: Long)

    fun frontmatter(text: String): Map<String, String> {
        if (!text.startsWith("---")) return emptyMap()
        val end = text.indexOf("\n---", 3).takeIf { it > 0 } ?: return emptyMap()
        return text.substring(3, end).lines().mapNotNull { l ->
            val k = l.substringBefore(':').trim(); val v = l.substringAfter(':', "").trim().trim('"', '\'')
            if (k.isNotBlank() && v.isNotBlank() && !l.startsWith(" ")) k to v else null
        }.toMap()
    }

    /** Prefer canonical skill folders over the per-tool copies many repos ship (.cursor, .gemini, …). */
    private fun skillRank(path: String) = when {
        path.startsWith("skills/") -> 0
        path.startsWith(".claude/skills/") -> 1
        path.startsWith(".agents/skills/") -> 2
        path.startsWith(".") -> 5
        else -> 3
    }

    /**
     * Builds a manifest for a repo without one. [readText] fetches a repo file (used only for frontmatter).
     * Returns manifest + the files to download.
     */
    suspend fun generate(repo: String, tree: List<Entry>, readText: suspend (String) -> String?): Pair<Manifest, List<String>> {
        val id = repo.lowercase().replace('/', '.')
        val name = repo.substringAfter('/')
        val files = mutableListOf<String>()

        // Skills: one per skill-folder name, canonical copy wins; include the folder's reference files.
        val skillMds = tree.filter { it.path.endsWith("/SKILL.md") && !it.path.contains("benchmark") }
            .groupBy { it.path.removeSuffix("/SKILL.md").substringAfterLast('/') }
            .map { (_, v) -> v.minBy { skillRank(it.path) } }
        val skills = skillMds.map { e ->
            val dir = e.path.removeSuffix("SKILL.md")
            tree.filter { it.path.startsWith(dir) && it.path.substringAfterLast('.', "") in TEXT }.forEach { files += it.path }
            val fm = frontmatter(readText(e.path).orEmpty())
            ExtSkill(fm["name"] ?: dir.trimEnd('/').substringAfterLast('/'), e.path, fm["description"].orEmpty())
        }

        // Agents: persona markdown with name + description frontmatter (Agency Agents style), outside docs/tooling folders.
        val skip = setOf("docs", "scripts", "examples", "integrations", "test", "tests", ".github")
        val agentCandidates = if (skills.isNotEmpty()) emptyList() else tree.filter { e ->
            e.path.endsWith(".md") && '/' in e.path && !e.path.startsWith(".") &&
                e.path.substringBefore('/') !in skip && !e.path.substringAfterLast('/').uppercase().startsWith("README") &&
                !e.path.substringAfterLast('/').uppercase().startsWith("CONTRIBUTING")
        }.take(MAX_FILES)
        val agents = coroutineScope {
            val gate = Semaphore(8)
            agentCandidates.map { e -> async { gate.withPermit {
                val fm = frontmatter(readText(e.path).orEmpty())
                if (fm["name"] != null && fm["description"] != null) ExtAgent(fm["name"]!!, e.path, fm["description"]!!.take(300)) else null
            } } }.awaitAll().filterNotNull()
        }
        agents.forEach { files += it.file }

        // Python package with no skills/agents: install it with pip at this exact commit; no tool is invented.
        val pip = if (skills.isEmpty() && agents.isEmpty() && tree.any { it.path == "pyproject.toml" || it.path == "setup.py" })
            listOf("git+https://github.com/$repo") else emptyList()

        val type = when { skills.isNotEmpty() && agents.isEmpty() -> "skill"; agents.isNotEmpty() -> "agent"; pip.isNotEmpty() -> "package"; else -> "skill" }
        return Manifest(id, name, "git", type, "Imported from github.com/$repo", skills, agents, emptyList(), ExtDeps(pip = pip),
            if (pip.isNotEmpty()) listOf("network", "linux.exec") else emptyList()) to files.distinct()
    }

    fun commands(m: Manifest, sha: String, repo: String): List<String> = buildList {
        if (m.dependencies.apt.isNotEmpty()) add("apt-get update && apt-get install -y " + m.dependencies.apt.joinToString(" ") { shellSafe(it) })
        if (m.dependencies.pip.isNotEmpty()) {
            if (m.dependencies.apt.none { it.startsWith("python3") }) add("apt-get update && apt-get install -y python3 python3-pip git")
            add("pip3 install --break-system-packages " + m.dependencies.pip.joinToString(" ") {
                shellSafe(if (it == "git+https://github.com/$repo") "git+https://github.com/$repo@$sha" else it) // pin to the inspected commit
            })
        }
    }

    /** Package names only: letters, digits and a few separators — nothing a shell would interpret. */
    fun shellSafe(s: String): String {
        require(Regex("[A-Za-z0-9._+:/@=<>~-]+").matches(s) && !s.contains("..")) { "unsafe package spec: $s" }
        return "'$s'"
    }
}

/** Ready-made manifests for useful repos that ship none (the doc's "registry"). */
object Registry {
    val featured = listOf(
        "DietrichGebert/ponytail" to "Lazy-senior-dev coding discipline (skills)",
        "pbakaus/impeccable" to "Design and UI quality skill",
        "msitarzewski/agency-agents" to "~300 specialist agent personas",
        "D4Vinci/Scrapling" to "Robust web scraping tool",
    )

    private val SCRAPLING_TOOL = """
import json, sys
from scrapling.fetchers import Fetcher
a = json.loads(sys.argv[1])
page = Fetcher.get(a["url"], stealthy_headers=True)
sel = a.get("selector") or ""
items = page.css(sel) if sel else [page]
out = [(i.get_all_text(separator=" ", strip=True) or "")[:2000] for i in items[:40]]
print(json.dumps({"status": page.status, "count": len(out), "items": out}, ensure_ascii=False))
""".trim()

    fun manifestFor(repo: String): Manifest? = when (repo.lowercase()) {
        "d4vinci/scrapling" -> Manifest("d4vinci.scrapling", "Scrapling", "pip", "tool", "Adaptive web scraping (fetch + CSS extraction).",
            tools = listOf(ExtTool("scrapling_extract", "Fetch a web page with Scrapling and extract text by CSS selector (robust to bot checks).",
                inline = SCRAPLING_TOOL, params = mapOf("url" to "http(s) URL", "selector" to "CSS selector, optional"), required = listOf("url"))),
            dependencies = ExtDeps(apt = listOf("python3", "python3-pip"), pip = listOf("scrapling", "curl_cffi")),
            permissions = listOf("network", "linux.exec"))
        else -> null
    }
}

/** Fetches, plans, installs, updates and removes extensions. Files live in agentic-os/extensions (visible in Linux). */
class ExtensionManager(private val root: File, private val token: () -> String) {
    val dir = File(root, "agentic-os/extensions").apply { mkdirs() }

    private fun headers() = buildMap {
        put("Accept", "application/vnd.github+json")
        token().takeIf { it.isNotBlank() }?.let { put("Authorization", "Bearer $it") }
    }

    /** "owner/repo", "https://github.com/owner/repo", or ".../tree/<ref>" → (repo, ref?) */
    fun parse(input: String): Pair<String, String?> {
        val t = input.trim().removePrefix("https://").removePrefix("http://").removePrefix("github.com/").trimEnd('/').removeSuffix(".git")
        val parts = t.split('/')
        val ok = Regex("[A-Za-z0-9_.-]+")
        require(parts.size >= 2 && ok.matches(parts[0]) && ok.matches(parts[1]) && parts[1] != "..") { "Use owner/repo or a github.com link" }
        val ref = if (parts.size >= 4 && parts[2] == "tree") parts.drop(3).joinToString("/") else null
        return "${parts[0]}/${parts[1]}" to ref
    }

    private suspend fun api(path: String): JsonObject {
        val r = httpCall("https://api.github.com$path", headers = headers())
        if (r.code == 403 || r.code == 429) error("GitHub rate limit — add a GitHub token in Settings")
        if (r.code != 200) error("GitHub HTTP ${r.code} for $path")
        return json.parseToJsonElement(r.body).jsonObject
    }

    private suspend fun raw(repo: String, sha: String, path: String): String? {
        val r = httpCall("https://raw.githubusercontent.com/$repo/$sha/" + path.split('/').joinToString("/") { java.net.URLEncoder.encode(it, "UTF-8").replace("+", "%20") })
        return if (r.code == 200) r.body else null
    }

    suspend fun inspect(input: String): InstallPlan = withContext(Dispatchers.IO) {
        val (repo, ref0) = parse(input)
        val ref = ref0 ?: api("/repos/$repo").str("default_branch") ?: "main"
        val sha = api("/repos/$repo/commits/$ref").str("sha") ?: error("can't resolve $ref")
        val treeJ = api("/repos/$repo/git/trees/$sha?recursive=1")
        val tree = (treeJ["tree"] as? JsonArray).orEmpty().mapNotNull { e ->
            val o = e.jsonObject
            if (o.str("type") == "blob") Importer.Entry(o.str("path")!!, o["size"]?.toString()?.toLongOrNull() ?: 0) else null
        }
        val warnings = mutableListOf<String>()
        if ((treeJ["truncated"]?.toString()) == "true") warnings += "Repository is very large; only part of it was scanned."
        val sizes = tree.associate { it.path to it.size }

        val own = tree.firstOrNull { it.path == "syntra-extension.json" }?.let { raw(repo, sha, it.path) }
        val (manifest, files, generated) = when {
            own != null -> {
                val m = json.decodeFromString(Manifest.serializer(), own)
                Triple(m, (m.skills.map { it.file } + m.agents.map { it.file } + m.tools.map { it.entry }).filter { it.isNotBlank() }, false)
            }
            Registry.manifestFor(repo) != null -> Triple(Registry.manifestFor(repo)!!, emptyList<String>(), true).also { warnings += "Manifest supplied by Syntra's registry." }
            else -> Importer.generate(repo, tree) { p -> raw(repo, sha, p) }.let { (m, f) -> Triple(m, f, true) }
        }
        manifest.mcp.forEach { require(it.url.startsWith("https://") && it.token.isBlank()) { "MCP server ${it.name} must use https and ship no token" } }
        if (manifest.mcp.isNotEmpty()) warnings += "Connects MCP servers: " + manifest.mcp.joinToString { "${it.name} (${it.url})" }
        if (manifest.skills.isEmpty() && manifest.agents.isEmpty() && manifest.tools.isEmpty() && manifest.dependencies.pip.isEmpty() && manifest.mcp.isEmpty())
            warnings += "Nothing Syntra can use was found (no SKILL.md, agent personas, tools or Python package)."
        var bytes = 0L
        val kept = files.filter { p -> val s = sizes[p] ?: 0; if (bytes + s > 6_000_000L) false else { bytes += s; true } }
        if (kept.size < files.size) warnings += "Skipped ${files.size - kept.size} files over the 6 MB limit."
        val scripts = tree.map { it.path }.filter { it.endsWith(".sh") || it.endsWith("install.py") || it.endsWith(".ps1") }.take(20)
        InstallPlan(repo, sha, manifest, generated, kept, bytes, Importer.commands(manifest, sha, repo), warnings, scripts)
    }

    /** Downloads files at the pinned commit. Dependencies are installed separately (in Linux) by the caller. */
    suspend fun install(plan: InstallPlan, progress: (String) -> Unit): InstalledExt = withContext(Dispatchers.IO) {
        val d = File(dir, plan.manifest.id).apply { deleteRecursively(); mkdirs() }
        coroutineScope {
            val gate = Semaphore(8); var done = 0
            plan.files.map { p -> async { gate.withPermit {
                val text = raw(plan.repo, plan.sha, p) ?: error("download failed: $p")
                val f = File(d, p).canonicalFile
                require(f.path.startsWith(d.canonicalPath)) { "bad path $p" }
                f.parentFile?.mkdirs(); f.writeText(text)
                synchronized(this@ExtensionManager) { done++; if (done % 10 == 0) progress("Downloaded $done/${plan.files.size} files") }
            } } }.awaitAll()
        }
        // Tool scripts: inline (registry) or downloaded entry, placed where the Linux runtime finds them.
        plan.manifest.tools.forEach { t ->
            val f = File(d, "tools/${t.name}.${if (t.runtime == "linux-shell") "sh" else "py"}")
            f.parentFile?.mkdirs()
            f.writeText(if (t.inline.isNotBlank()) t.inline else File(d, t.entry).takeIf { it.exists() }?.readText() ?: error("missing tool entry ${t.entry}"))
        }
        File(d, "syntra-extension.json").writeText(json.encodeToString(Manifest.serializer(), plan.manifest))
        InstalledExt(plan.manifest, plan.repo, plan.sha, toolsReady = plan.commands.isEmpty())
    }

    fun remove(id: String) { File(dir, id).deleteRecursively() }

    fun read(id: String, file: String): String? = File(dir, "$id/$file").takeIf { it.isFile }?.readText()

    /** Latest commit of the installed ref, to offer an update when it differs. */
    suspend fun latestSha(repo: String): String? = runCatching {
        val ref = api("/repos/$repo").str("default_branch") ?: "main"
        api("/repos/$repo/commits/$ref").str("sha")
    }.getOrNull()
}

/** Enabled extension tools for the agent: tool name → (extension id, definition). Set by the app on load/install. */
object ExtRuntime {
    @Volatile var tools: Map<String, Pair<String, ExtTool>> = emptyMap()

    fun definitions(): List<JsonObject> = tools.values.map { (_, t) ->
        kotlinx.serialization.json.buildJsonObject {
            put("type", kotlinx.serialization.json.JsonPrimitive("function"))
            put("function", kotlinx.serialization.json.buildJsonObject {
                put("name", kotlinx.serialization.json.JsonPrimitive(t.name))
                put("description", kotlinx.serialization.json.JsonPrimitive("[extension] " + t.description))
                put("parameters", kotlinx.serialization.json.buildJsonObject {
                    put("type", kotlinx.serialization.json.JsonPrimitive("object"))
                    put("properties", kotlinx.serialization.json.JsonObject(t.params.mapValues { (_, d) ->
                        kotlinx.serialization.json.buildJsonObject { put("type", kotlinx.serialization.json.JsonPrimitive("string")); put("description", kotlinx.serialization.json.JsonPrimitive(d)) } }))
                    put("required", kotlinx.serialization.json.JsonArray(t.required.map { kotlinx.serialization.json.JsonPrimitive(it) }))
                })
            })
        }
    }

    /** Shell command that runs a tool inside Ubuntu with its JSON arguments as argv[1]. */
    fun command(extId: String, t: ExtTool, argsJson: String): String {
        val q = "'" + argsJson.replace("'", "'\\''") + "'"
        val file = "tools/${t.name}.${if (t.runtime == "linux-shell") "sh" else "py"}"
        val run = if (t.runtime == "linux-shell") "bash $file" else "python3 $file"
        return "cd /root/agentic-os/extensions/$extId && timeout ${t.timeoutSec} $run $q"
    }
}
